import type { Bill, BillLineItem, BillLineItemType } from '../types/bill.types';
function lineItem(billId: string, index: number, type: BillLineItemType, label: string, amount: number): BillLineItem {
    return {
        lineItemId: `${billId}:line-item:${index}`,
        type,
        label,
        labelMessageKey: `resident.billing.lineItem.${type}`,
        amount,
        currencyCode: 'INR',
        isCredit: amount < 0,
    };
}
