import type { EmergencyContact, EmergencyResponder, EmergencyIncident, EmergencyTimelineEvent, EmergencyType, EmergencySeverity, EmergencyStatus, EmergencyResponderRole, ResponderStatus, FireAlertType, SecurityThreatType, EmergencyContactRelationship } from '../../../../shared/types/emergency.types';
import type { SeniorCareProfile, SeniorDailyCheckIn, SeniorInactivityAlert, SeniorCareStatus, SeniorCheckInStatus } from '../../../../shared/types/seniorCare.types';
import type { EmergencyVolunteer, VolunteerAlert, VolunteerType, VolunteerAvailability, VolunteerVerificationStatus, VolunteerAlertStatus } from '../../../../shared/types/volunteer.types';
import type { EmergencyBroadcast, SafetyInstruction, SafetyDrillRecord, PostIncidentReview, EmergencyAuditLog, EmergencyBroadcastType, EmergencyBroadcastStatus, SafetyInstructionCategory, SafetyDrillType, SafetyDrillStatus, PostIncidentReviewStatus } from '../../../../shared/types/safety.types';
import type { EmergencyContactDTO, EmergencyResponderDTO, EmergencyIncidentDTO, EmergencyTimelineEventDTO, SeniorCareProfileDTO, SeniorDailyCheckInDTO, SeniorInactivityAlertDTO, EmergencyVolunteerDTO, VolunteerAlertDTO, EmergencyBroadcastDTO, SafetyInstructionDTO, SafetyDrillRecordDTO, PostIncidentReviewDTO, EmergencyAuditLogDTO } from './emergencySafety.dto';
import { includeWhenPresent } from "../../../../shared/utils/presentProperty";
import type { Absent } from "../../../../shared/types/absence.types";
export const emergencyMappers = {
    toContact: (dto: EmergencyContactDTO): EmergencyContact => ({
        id: dto.id,
        name: dto.name,
        relationship: dto.relationship as EmergencyContactRelationship,
        mobileNumber: dto.mobile_number,
        mobileMasked: dto.mobile_masked,
        priority: dto.priority,
        notifyForAll: dto.notify_for_all,
        notifyForSeniorOnly: dto.notify_for_senior_only,
        consentConfirmed: dto.consent_confirmed,
        createdAt: dto.created_at
    }),
    toResponder: (dto: EmergencyResponderDTO): EmergencyResponder => ({
        id: dto.id,
        name: dto.name,
        role: dto.role as EmergencyResponderRole,
        ...includeWhenPresent("mobileMasked", dto.mobile_masked),
        status: dto.status as ResponderStatus,
        ...includeWhenPresent("etaMinutes", dto.eta_minutes),
        assignedAt: dto.assigned_at,
        ...includeWhenPresent("acknowledgedAt", dto.acknowledged_at),
        ...includeWhenPresent("reachedAt", dto.reached_at)
    }),
    toIncident: (dto: EmergencyIncidentDTO): EmergencyIncident => ({
        id: dto.id,
        incidentNumber: dto.incident_number,
        emergencyType: dto.emergency_type as EmergencyType,
        severity: dto.severity as EmergencySeverity,
        status: dto.status as EmergencyStatus,
        reportedByUserId: dto.reported_by_user_id,
        reportedByUserName: dto.reported_by_user_name,
        reportedByUserMobileMasked: dto.reported_by_user_mobile_masked,
        unitId: dto.unit_id,
        flatNumber: dto.flat_number,
        tower: dto.tower,
        location: dto.location,
        ...includeWhenPresent("description", dto.description),
        isSeniorCitizen: dto.is_senior_citizen,
        needAmbulance: dto.need_ambulance,
        needVolunteer: dto.need_volunteer,
        notifyFamily: dto.notify_family,
        isPrivate: dto.is_private,
        ...includeWhenPresent("fireType", dto.fire_type as FireAlertType | Absent),
        ...includeWhenPresent("isPeopleTrapped", dto.is_people_trapped),
        ...includeWhenPresent("liftNumber", dto.lift_number),
        ...includeWhenPresent("numberOfPeopleStuck", dto.number_of_people_stuck),
        ...includeWhenPresent("threatType", dto.threat_type as SecurityThreatType | Absent),
        responders: dto.responders.map(emergencyMappers.toResponder),
        createdAt: dto.created_at,
        ...includeWhenPresent("resolvedAt", dto.resolved_at),
        ...includeWhenPresent("closedAt", dto.closed_at),
        ...includeWhenPresent("closureSummary", dto.closure_summary)
    }),
    toTimelineEvent: (dto: EmergencyTimelineEventDTO): EmergencyTimelineEvent => ({
        id: dto.id,
        incidentId: dto.incident_id,
        timestamp: dto.timestamp,
        actorId: dto.actor_id,
        actorName: dto.actor_name,
        actorRole: dto.actor_role,
        eventType: dto.event_type,
        ...includeWhenPresent("note", dto.note),
        source: dto.source as EmergencyTimelineEvent['source']
    }),
    toSeniorProfile: (dto: SeniorCareProfileDTO): SeniorCareProfile => ({
        id: dto.id,
        residentId: dto.resident_id,
        name: dto.name,
        unitId: dto.unit_id,
        flatNumber: dto.flat_number,
        tower: dto.tower,
        seniorCareStatus: dto.senior_care_status as SeniorCareStatus,
        familyConnectEnabled: dto.family_connect_enabled,
        dailyCheckInEnabled: dto.daily_check_in_enabled,
        ...includeWhenPresent("preferredHelpType", dto.preferred_help_type),
        priorityComplaintEnabled: dto.priority_complaint_enabled,
        ...includeWhenPresent("securityCheckCallPreference", dto.security_check_call_preference),
        consentConfirmed: dto.consent_confirmed,
        ...includeWhenPresent("consentDate", dto.consent_date),
        createdAt: dto.created_at,
        ...includeWhenPresent("updatedAt", dto.updated_at)
    }),
    toSeniorCheckIn: (dto: SeniorDailyCheckInDTO): SeniorDailyCheckIn => ({
        id: dto.id,
        seniorId: dto.senior_id,
        seniorName: dto.senior_name,
        flatNumber: dto.flat_number,
        tower: dto.tower,
        date: dto.date,
        status: dto.status as SeniorCheckInStatus,
        ...includeWhenPresent("checkInTime", dto.check_in_time),
        ...includeWhenPresent("notes", dto.notes),
        notifiedFamily: dto.notified_family
    }),
    toSeniorInactivityAlert: (dto: SeniorInactivityAlertDTO): SeniorInactivityAlert => ({
        id: dto.id,
        seniorId: dto.senior_id,
        seniorName: dto.senior_name,
        unitId: dto.unit_id,
        flatNumber: dto.flat_number,
        tower: dto.tower,
        missedCheckInTime: dto.missed_check_in_time,
        alertStatus: dto.alert_status as SeniorInactivityAlert['alertStatus'],
        familyNotified: dto.family_notified,
        securityCheckCallStatus: dto.security_check_call_status as SeniorInactivityAlert['securityCheckCallStatus'],
        ...includeWhenPresent("acknowledgedBy", dto.acknowledged_by),
        ...includeWhenPresent("acknowledgedAt", dto.acknowledged_at),
        ...includeWhenPresent("notes", dto.notes)
    }),
    toVolunteer: (dto: EmergencyVolunteerDTO): EmergencyVolunteer => ({
        id: dto.id,
        residentId: dto.resident_id,
        name: dto.name,
        volunteerType: dto.volunteer_type as VolunteerType,
        availability: dto.availability as VolunteerAvailability,
        tower: dto.tower,
        flatNumber: dto.flat_number,
        ...includeWhenPresent("skillsNote", dto.skills_note),
        verificationStatus: dto.verification_status as VolunteerVerificationStatus,
        contactVisibilityConsent: dto.contact_visibility_consent,
        mobileMasked: dto.mobile_masked,
        createdAt: dto.created_at
    }),
    toVolunteerAlert: (dto: VolunteerAlertDTO): VolunteerAlert => ({
        id: dto.id,
        incidentId: dto.incident_id,
        emergencyType: dto.emergency_type,
        location: dto.location,
        severity: dto.severity,
        volunteerId: dto.volunteer_id,
        volunteerName: dto.volunteer_name,
        status: dto.status as VolunteerAlertStatus,
        alertedAt: dto.alerted_at,
        ...includeWhenPresent("respondedAt", dto.responded_at),
        ...includeWhenPresent("responseNote", dto.response_note)
    }),
    toBroadcast: (dto: EmergencyBroadcastDTO): EmergencyBroadcast => ({
        id: dto.id,
        broadcastType: dto.broadcast_type as EmergencyBroadcastType,
        senderName: dto.sender_name,
        senderRole: dto.sender_role,
        message: dto.message,
        severity: dto.severity as EmergencyBroadcast['severity'],
        targetAudience: dto.target_audience,
        ...includeWhenPresent("affectedArea", dto.affected_area),
        status: dto.status as EmergencyBroadcastStatus,
        sentAt: dto.sent_at
    }),
    toSafetyInstruction: (dto: SafetyInstructionDTO): SafetyInstruction => ({
        id: dto.id,
        category: dto.category as SafetyInstructionCategory,
        title: dto.title,
        steps: dto.steps,
        emergencyNumbers: dto.emergency_numbers,
        audience: dto.audience,
        lastUpdatedAt: dto.last_updated_at
    }),
    toDrillRecord: (dto: SafetyDrillRecordDTO): SafetyDrillRecord => ({
        id: dto.id,
        drillType: dto.drill_type as SafetyDrillType,
        drillName: dto.drill_name,
        scheduledDate: dto.scheduled_date,
        targetArea: dto.target_area,
        participantsCount: dto.participants_count,
        status: dto.status as SafetyDrillStatus,
        ...includeWhenPresent("observations", dto.observations),
        ...includeWhenPresent("improvementActions", dto.improvement_actions),
        ...includeWhenPresent("completedAt", dto.completed_at)
    }),
    toPostIncidentReview: (dto: PostIncidentReviewDTO): PostIncidentReview => ({
        id: dto.id,
        incidentId: dto.incident_id,
        incidentNumber: dto.incident_number,
        emergencyType: dto.emergency_type,
        reviewOwnerName: dto.review_owner_name,
        whatHappened: dto.what_happened,
        responseTimeMinutes: dto.response_time_minutes,
        whatWorkedWell: dto.what_worked_well,
        whatFailed: dto.what_failed,
        followUpActions: dto.follow_up_actions,
        responsiblePerson: dto.responsible_person,
        ...includeWhenPresent("dueDate", dto.due_date),
        status: dto.status as PostIncidentReviewStatus,
        createdAt: dto.created_at
    }),
    toAuditLog: (dto: EmergencyAuditLogDTO): EmergencyAuditLog => ({
        id: dto.id,
        timestamp: dto.timestamp,
        actorId: dto.actor_id,
        actorName: dto.actor_name,
        actorRole: dto.actor_role,
        eventType: dto.event_type,
        entityReference: dto.entity_reference,
        correlationId: dto.correlation_id,
        metadata: dto.metadata
    })
};

